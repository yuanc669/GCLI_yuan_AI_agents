import os

path_configs = {
    "Path1_Aging": "老化基準分析 (Aging Base)",
    "Path2_Acute": "急性誘導期分析 (Acute Induction)",
    "Path3_Establishment": "模型定型分析 (DN Establishment)",
    "Path4_Progression": "病程進展分析 (Disease Progression)",
    "Path5_Driver": "驅動因子拆解 (Driver Dissection)",
    "Path6_Efficacy": "藥效評估分析 (Efficacy Evaluation)",
    "Path7_Global": "全景整合分析 (Global Integration)"
}

base_dir = r"100_Research/02_Active/DN_GaExo/02_Analysis/03_Pathology"
master_report_dir = r"100_Research/02_Active/DN_GaExo/02_Analysis/05_Integrated_Synthesis"
os.makedirs(master_report_dir, exist_ok=True)

master_content = "# DN_GaExo 專案：全路徑病理分析整合大師報告 (Master Report)\n\n"
master_content += "## 1. 專案概況\n本報告整合了 DN_GaExo 專案中 Path 1 至 Path 7 的所有 H&E 病理定量結果與視覺化圖表，旨在評估大蒜外泌體 (GaExo) 對糖尿病腎病變 (DN) 的保護效應。\n\n"

for path_id, title in path_configs.items():
    res_dir = os.path.join(base_dir, path_id, "02_Results")
    report_path = os.path.join(res_dir, f"{path_id}_Pathology_Report.md")
    
    # 1. Update individual MD report with images
    if os.path.exists(report_path):
        with open(report_path, "r", encoding="utf-8") as f:
            content = f.read()
        
        # Insert images before section 4
        img_section = f"### 📊 數據視覺化 (Visualization)\n"
        img_section += f"![Tubular Injury Score Plot](Tubular_Injury_Score_Plot.png)\n"
        img_section += f"![Glomerular Area Plot](Glomerular_Area_Plot.png)\n\n"
        
        if "## 4. 數據解讀" in content:
            new_content = content.replace("## 4. 數據解讀", img_section + "## 4. 數據解讀")
        else:
            new_content = content + "\n" + img_section
            
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(new_content)
    
    # 2. Add to Master Content
    rel_report_path = f"../03_Pathology/{path_id}/02_Results/{path_id}_Pathology_Report.md"
    master_content += f"### 📍 {title} ({path_id})\n"
    master_content += f"*   [查看詳細報告與原始數據]({rel_report_path})\n"
    master_content += f"![{path_id} Tubular Injury Score](../03_Pathology/{path_id}/02_Results/Tubular_Injury_Score_Plot.png)\n\n"

